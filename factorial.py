def factorial(n): 
    '''Возвращает факториал для заданного неотрицательного числа n
    
        Параметр: a (int) : число
    
        Возвращаемое значение: (int) : факториал n

        Пример вызова функции:
            factorial(5) -> 120'''
    if n == 0:
        return 1
    else: 
        return n * factorial(n - 1)